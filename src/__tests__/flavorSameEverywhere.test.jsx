// @vitest-environment jsdom
// FLAVOR-6: one profile everywhere. For the same recipe the Recipe Notebook card, an invent panel, the shared
// page and the server card (share-cards.json) lead with the same tastes, because they all call the same function
// (inventProfile.buildFlavorProfile over the curated labels and the aroma table).
//
// Legitimate differences, none of which changes the lead:
//  - the invent panel weighs the amounts it SUGGESTS for the ingredients the cook adds, not the recipe's own amounts;
//  - the Notebook overview shows each axis as a share of the total signal, the others show the axis score.
import { describe, it, expect, vi, beforeEach } from 'vitest';
import { render, screen, within, fireEvent } from '@testing-library/react';
import { readFileSync } from 'node:fs';

vi.mock('../hooks/useAuth.js', () => ({ default: () => ({ user: null, loading: false, authError: null, loginWithGoogle: vi.fn(), loginWithApple: vi.fn() }) }));
vi.mock('../hooks/useUserProfile.js', () => ({ default: () => ({ profile: {}, saveInvention: vi.fn() }) }));
import SharedRecipePage from '../components/SharedRecipePage.jsx';
import RecipeFlavorProfilesCard from '../components/RecipeFlavorProfilesCard.jsx';
import InventCocktail from '../components/InventCocktail.jsx';
import { SHARE_CHARTS_ENABLED } from '../data/shareTargets.js';
import { SEED_RECIPES } from '../data/seedRecipes.js';
import { RECIPE_DETAILS } from '../data/seedRecipeDetails.js';
import { resolveBuiltIn } from '../data/sharedRecipe.js';
import { profileForRecipe } from '../data/shareCardData.js';
import { parseAmountText } from '../data/amountGrams.js';
import { loadFlavorNodes } from '../../scripts/lib/flavorNodes.mjs';
import { buildPairingIndex } from '../data/recipePairingMatch.js';
import { buildRolePool } from '../data/cocktailRiff.js';
import serverCards from '../../functions/src/share/share-cards.json';

const codex = JSON.parse(readFileSync('public/data/cocktail_codex_v2.json', 'utf8'));
const data = { cocktails: codex.cocktails, families: codex.families, dishes: SEED_RECIPES, dishDetails: RECIPE_DETAILS };
const loadData = async (kind) => (kind === 'cocktail' ? { cocktails: data.cocktails, families: data.families } : { dishes: SEED_RECIPES, dishDetails: RECIPE_DETAILS });
const nodes = loadFlavorNodes();

const RECIPES = { negroni: ['cocktail', 'negroni'], 'beef-bolognese': ['dish', 'beef-bolognese'] };
const LEAD = 2; // how many leading bars must agree

const leadOf = (axes) => axes.slice(0, LEAD);
// AROMA-2: gin now leads with woody/fruity and Negroni's fruity and sweet bars tie (0.387 each), so which of two
// bars within TIE of each other comes second is not a disagreement between surfaces: the last lead place may be any bar tied with it.
const TIE = 0.005;
const sameLead = (axes, truthBars) => {
  const got = leadOf(axes);
  const want = truthBars.slice(0, LEAD);
  const last = want[LEAD - 1];
  const tied = truthBars.filter((b) => Math.abs(b.score - last.score) <= TIE).map((b) => b.axis);
  return got.slice(0, LEAD - 1).every((a, i) => a === want[i].axis) && tied.includes(got[LEAD - 1]);
};
const axisOf = (el, prefix) => el.getAttribute('data-testid').replace(prefix, '');

beforeEach(() => { global.fetch = vi.fn(() => Promise.resolve({ ok: false })); });

describe('the committed switch', () => {
  it('SHARE_CHARTS_ENABLED is on', () => { expect(SHARE_CHARTS_ENABLED).toBe(true); });
});

for (const [name, [kind, slug]] of Object.entries(RECIPES)) {
  describe(`${name}: the same lead on every surface`, () => {
    const recipe = resolveBuiltIn(kind, slug, data);
    const truth = profileForRecipe(recipe, nodes);
    const truthLead = leadOf(truth.bars.map((b) => b.axis));

    it('the reference profile has a real lead', () => {
      expect(truth.drawn).toBe(true);
      expect(truthLead.length).toBe(LEAD);
    });

    it('the Recipe Notebook card (overview bars, built from the recipe lines and amounts)', () => {
      const entries = recipe.lines.map((l) => ({ ingredient: l.key, amount: parseAmountText(l.amount) ? { raw: l.amount, ...parseAmountText(l.amount) } : { raw: l.amount } }));
      render(<RecipeFlavorProfilesCard bowlNames={entries.map((e) => e.ingredient)} bowlEntries={entries} nodes={nodes} edges={null} onClose={() => {}} />);
      const axes = screen.getAllByTestId('overview-bar').map((b) => b.getAttribute('data-axis'));
      expect(sameLead(axes, truth.bars)).toBe(true);
    });

    it('the shared page', async () => {
      render(<SharedRecipePage route={{ kind, slug }} loadData={loadData} loadNodes={async () => nodes} />);
      const chart = await screen.findByTestId('shared-profile');
      const axes = within(chart).getAllByRole('listitem').map((li) => axisOf(li, 'shared-profile-bar-'));
      expect(sameLead(axes, truth.bars)).toBe(true);
    });

    it('the server card (share-cards.json, generated by scripts/buildShareIndex.mjs)', () => {
      const bars = serverCards[`${kind}/${slug}`].bars;
      expect(bars.map((b) => b.label.toLowerCase()).slice(0, LEAD)).toEqual(truth.bars.slice(0, LEAD).map((b) => b.label.toLowerCase()));
      expect(bars[0].score).toBeCloseTo(truth.bars[0].score, 2);
    });
  });
}

describe('negroni: the Cocktail Lab invent panel leads with the same tastes', () => {
  const roles = { gin: { role: 'spirit' }, campari: { role: 'amaro_liqueur' }, 'sweet vermouth': { role: 'vermouth' } };
  const index = buildPairingIndex([{ source: 'gin', target: 'campari', strength: 0.8, known: true }, { source: 'campari', target: 'sweet vermouth', strength: 0.9, known: true }], Object.keys(roles));
  const pool = buildRolePool(roles, index.names);
  const families = [{ id: 4, name: 'Aromatic Stirred', color: '#7c3aed' }];

  it('gin + campari + sweet vermouth: bitter and sweet lead, as on the recipe', () => {
    render(<InventCocktail bar={['gin', 'campari', 'sweet vermouth']} cocktails={[]} families={families} roles={roles} pool={pool} pairingIndex={index} nodes={nodes} onClose={vi.fn()} />);
    const add = (text) => {
      fireEvent.change(screen.getByTestId('invent-list-add-input'), { target: { value: text } });
      fireEvent.submit(screen.getByTestId('invent-list-add-input').closest('form'));
    };
    fireEvent.change(screen.getByTestId('invent-start-input'), { target: { value: 'gin' } });
    fireEvent.submit(screen.getByTestId('invent-start-input').closest('form'));
    add('campari');
    add('sweet vermouth');
    const bars = screen.getAllByTestId(/^invent-profile-bar-/).map((b) => axisOf(b, 'invent-profile-bar-'));
    const recipe = resolveBuiltIn('cocktail', 'negroni', data);
    const truthTastes = profileForRecipe(recipe, nodes).bars.map((b) => b.axis).filter((a) => !a.startsWith('odor_')).slice(0, 2);
    expect(bars.filter((a) => !a.startsWith('odor_')).slice(0, 2).sort()).toEqual([...truthTastes].sort());
  });
});
